/**
 * Generate N order line items
 */
export function generateOrderItems(count: number) {
  const result = [];
  const quantities = [1, 2, 3, 4, 5, 8, 10];

  for (let i = 0; i < count; i++) {
    const base = baseProducts[i % baseProducts.length];
    const qty = quantities[(i * 3 + 2) % quantities.length];
    const unitPrice = base.unitPrice;
    result.push({
      sku: `${base.sku}-${String(Math.floor(i / baseProducts.length) + 1).padStart(2, '0')}`,
      productName: base.productName,
      quantity: qty,
      unitPrice: unitPrice,
      amount: qty * unitPrice,
    });
  }
  return result;
}

